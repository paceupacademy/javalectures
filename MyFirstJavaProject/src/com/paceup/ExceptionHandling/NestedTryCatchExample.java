package com.paceup.ExceptionHandling;

/**
 * NestedTryCatchExample:
 * ----------------------
 *
 * Exception Handling Basics:
 * --------------------------
 * - A try block contains code that may throw exceptions.
 * - A catch block handles exceptions thrown inside the try block.
 * - Nested try-catch allows handling different risky operations separately.
 *
 * Key Points:
 * -----------
 * 1. Nested try-catch:
 *    - One try-catch block can be placed inside another try block.
 *    - Useful when multiple independent operations may throw
 *      different exceptions.
 *
 * 2. Execution Flow:
 *    - Exception in inner try -> Inner catch handles it first.
 *    - Exception in outer try -> Outer catch handles it.
 *    - If inner catch rethrows an exception, the outer catch can
 *      handle the propagated exception.
 *
 * 3. Common Runtime Exceptions:
 *    - ArithmeticException
 *         -> divide by zero.
 *
 *    - ArrayIndexOutOfBoundsException
 *         -> invalid array index access.
 *
 * 4. Exception Chaining:
 *    - initCause() is used to preserve the original exception.
 *    - Helps debugging by maintaining root cause information.
 *
 * 5. Best Practice:
 *    - Handle exceptions at the appropriate level.
 *    - Preserve original exceptions whenever rethrowing.
 *
 * ---------------------------------------------------------------------------
 * CURRENT EXECUTION:
 * ---------------------------------------------------------------------------
 * Since:
 *
 *      int result = 10 / 0;
 *
 * throws ArithmeticException immediately,
 * the nested try block never executes.
 *
 * Therefore:
 * - ArrayIndexOutOfBoundsException never occurs.
 * - Inner catch never executes.
 * - Control directly goes to outer catch.
 *
 * ---------------------------------------------------------------------------
 * To test nested try-catch:
 * ---------------------------------------------------------------------------
 *
 * Change:
 *
 *      int result = 10 / 2;
 *
 * Then inner try block executes and demonstrates nested handling.
 */
public class NestedTryCatchExample {

    public static void main(String[] args) {

        /*
         * =====================================================================
         * OUTER TRY BLOCK
         * =====================================================================
         *
         * Purpose:
         * --------
         * Handles exceptions generated by:
         *
         * - Arithmetic operations
         * - Propagated exceptions from inner try-catch
         *
         * Execution Pipeline:
         *
         * Outer Try
         *      |
         *      V
         * Arithmetic Operation
         *      |
         *      V
         * Nested Try-Catch
         *      |
         *      V
         * Outer Catch (if required)
         *
         * =====================================================================
         */
        try {

            /*
             * Array Initialization
             *
             * Valid Indexes:
             * ----------------
             * arr[0] = 1
             * arr[1] = 2
             * arr[2] = 3
             */
            int[] arr = {1, 2, 3};

            /*
             * =================================================================
             * ARITHMETIC EXCEPTION
             * =================================================================
             *
             * Division by zero.
             *
             * JVM Behavior:
             *
             * 10 / 0
             *    |
             *    V
             * ArithmeticException
             *    |
             *    V
             * Outer Catch Block
             *
             * NOTE:
             * -----
             * Since exception occurs here,
             * inner try block never executes.
             */
            int result = 10 / 4;

            /*
             * =================================================================
             * INNER TRY BLOCK
             * =================================================================
             *
             * This block executes ONLY if
             * the above arithmetic operation succeeds.
             *
             * Since 10/0 throws an exception,
             * this code is currently unreachable.
             *
             * =================================================================
             */
            try {

                /*
                 * Invalid Index Access
                 *
                 * Array Size = 3
                 *
                 * Valid:
                 * arr[0]
                 * arr[1]
                 * arr[2]
                 *
                 * Invalid:
                 * arr[5]
                 *
                 * Generates:
                 * ArrayIndexOutOfBoundsException
                 */
                System.out.println(arr[5]);

            }
            catch (ArrayIndexOutOfBoundsException e) {

                /*
                 * =============================================================
                 * EXCEPTION CHAINING
                 * =============================================================
                 *
                 * Create a custom exception object.
                 *
                 * Purpose:
                 * Provide more meaningful business-level message while
                 * retaining original exception details.
                 */
                ArrayIndexOutOfBoundsException arrEx =
                        new ArrayIndexOutOfBoundsException(
                                "Index out of limit entered"
                        );

                /*
                 * Store original exception as root cause.
                 *
                 * Benefits:
                 * ----------
                 * Easier debugging.
                 * Preserves complete exception history.
                 */
                arrEx.initCause(e);

                /*
                 * Rethrow exception.
                 *
                 * Since this exception is not handled here,
                 * it propagates to outer catch block.
                 */
                throw arrEx;

                /*
                 * Alternative:
                 *
                 * System.out.println(
                 *      "Inner catch: " + e.getMessage());
                 *
                 * This would handle the exception locally.
                 */
            }

        }
        catch (Exception e) {

            /*
             * =================================================================
             * OUTER CATCH BLOCK
             * =================================================================
             *
             * Handles:
             *
             * 1. ArithmeticException
             * 2. Re-thrown ArrayIndexOutOfBoundsException
             * 3. Any subclass of Exception
             *
             * Since current code contains:
             *
             *      int result = 10 / 0;
             *
             * this catch receives:
             *
             *      ArithmeticException
             *
             * =================================================================
             */

            e.printStackTrace();

            /*
             * ================================================================
             * EXCEPTION WRAPPING EXAMPLE
             * ================================================================
             *
             * Alternative approach:
             *
             * Wrap ArithmeticException
             * inside another exception.
             *
             * Useful in enterprise applications
             * where low-level details are hidden.
             */

            /*
            ArithmeticException newEx =
                    new ArithmeticException(
                            "Division failed due to divide by 0"
                    );

            newEx.initCause(e);

            throw newEx;
            */
        }

        /*
         * Program continues because exception
         * has been handled successfully.
         */
        System.out.println("TRY-Catch executed");
    }
}